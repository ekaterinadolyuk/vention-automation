// Relational or comparison operators. Result = boolean

// > - more than
// < - less than
// >= - less than equal
// <= - less than equal

var result = 6 <= 5
console.log(result)

// Equalty operators. Result = boolean

var x = 1
console.log(x == '1') // lose comparison: comparing not data type, but the value itself
console.log(x === 1) // strict comparison: checking the value and the data type
